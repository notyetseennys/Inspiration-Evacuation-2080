  const cache = new Map();
  function url(shape, pal) {
    pal = pal || {};
    const key = shape + JSON.stringify(pal);
    if (cache.has(key)) return cache.get(key);
    const raw = SHAPES[shape] || SHAPES.gem;
    const sz = raw.length > 12 || (raw[0] && raw[0].length > 12) ? 16 : 12;
    const rows = raw.slice(0, sz).map((r) => r.padEnd(sz, '.').slice(0, sz));
    while (rows.length < sz) rows.push('.'.repeat(sz));
    // 水平置中
    let min = sz, max = -1;
    rows.forEach((r) => { for (let i = 0; i < sz; i++) if (r[i] !== '.') { min = Math.min(min, i); max = Math.max(max, i); } });
    const off = max >= min ? Math.floor((sz - (max - min + 1)) / 2) - min : 0;
    const P = Object.assign({ k: '#14141c', a: '#8e9bb0', b: '#4a5568', c: '#e8edf6', w: '#ffffff' }, pal);
    const cv = document.createElement('canvas');
    cv.width = sz; cv.height = sz;
    const x = cv.getContext('2d');
    rows.forEach((r, j) => { for (let i = 0; i < sz; i++) { const ch = r[i]; if (ch === '.' || !P[ch]) continue; x.fillStyle = P[ch]; x.fillRect(i + off, j, 1, 1); } });
    const u = cv.toDataURL();
    cache.set(key, u);
    return u;
  }
