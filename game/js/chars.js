      const name = P.hasSprite('bust_' + id) ? 'bust_' + id : P.hasSprite('ch_' + id) ? 'ch_' + id : 'player';
      const src = P.spriteCanvas(name, locked ? { tint: '#1b2233' } : {});
      const pxScale = Math.max(2, Math.round(sc / 2));
      const cv = document.createElement('canvas');
