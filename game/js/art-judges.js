  const cache = new Map();
  function renderPortrait(item) {
    if (!item) return '';
    if (cache.has(item.id)) return cache.get(item.id);
    const sz = 32;
    const P = item.pal;
    const cv = document.createElement('canvas');
    cv.width = sz;
    cv.height = sz;
    const x = cv.getContext('2d');
    item.px.slice(0, sz).forEach((row, j) => {
      for (let i = 0; i < sz && i < row.length; i++) {
        const ch = row[i];
        if (ch === '.' || !P[ch]) continue;
        x.fillStyle = P[ch];
        x.fillRect(i, j, 1, 1);
      }
    });
    const u = cv.toDataURL();
    cache.set(item.id, u);
    return u;
  }

